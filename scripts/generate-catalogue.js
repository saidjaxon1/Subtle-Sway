/* ============================================================
   Subtle Sway — product catalogue
   Writes CATALOGUE.md from products.json and posts.json: what is
   in the shop, which rooms each piece suits, where it appears, and
   which pieces the articles still need.
   Run locally with:  node scripts/generate-catalogue.js
   Also runs automatically via .github/workflows/sitemap.yml
   ============================================================ */

var fs = require("fs");
var path = require("path");

var root = path.join(__dirname, "..");
var products = JSON.parse(fs.readFileSync(path.join(root, "products.json"), "utf8"));
var posts = JSON.parse(fs.readFileSync(path.join(root, "posts.json"), "utf8"));

var ROOMS = ["Living Room", "Bedroom", "Dining Room", "Entryway", "Home Office", "Kitchen"];

// Pull the ASIN out of an Amazon link so each product is easy to look up.
function asin(link) {
  var match = String(link).match(/\/(?:dp|gp\/aw\/d)\/([A-Z0-9]{10})/);
  return match ? match[1] : "—";
}

// Which articles link to each product.
var usedIn = {};
posts.forEach(function (post) {
  (post.content || []).forEach(function (block) {
    if (block.type !== "shoplist") return;
    block.slugs.forEach(function (slug) {
      if (!usedIn[slug]) usedIn[slug] = [];
      if (usedIn[slug].indexOf(post.title) === -1) usedIn[slug].push(post.title);
    });
  });
});

var kinds = [];
products.forEach(function (product) {
  if (product.subcategory && kinds.indexOf(product.subcategory) === -1) kinds.push(product.subcategory);
});

var lines = [];
lines.push("# Product catalogue");
lines.push("");
lines.push("A working reference for the admin panel: what is in the shop, which rooms each piece");
lines.push("suits, and where it appears. Generated by `scripts/generate-catalogue.js`, so it stays");
lines.push("in step with `products.json` — do not edit it by hand.");
lines.push("");
lines.push("_Last generated: " + new Date().toISOString().slice(0, 10) + "_");
lines.push("");

/* At a glance */
var noImage = products.filter(function (p) { return !p.image; }).length;
var noPrice = products.filter(function (p) { return !p.price; }).length;
var noRooms = products.filter(function (p) { return !(p.rooms || []).length; }).length;

lines.push("## At a glance");
lines.push("");
lines.push("- **" + products.length + " products** in the shop");
lines.push("- By kind: " + kinds.map(function (kind) {
  return kind + " " + products.filter(function (p) { return p.subcategory === kind; }).length;
}).join(" · "));
lines.push("- Missing a photo: **" + noImage + "** · missing a price: **" + noPrice + "** · no rooms set: **" + noRooms + "**");
lines.push("");

/* Room coverage */
lines.push("## What each room can be furnished with");
lines.push("");
lines.push("| Room | " + kinds.join(" | ") + " | Total |");
lines.push("|---" + kinds.map(function () { return "|---"; }).join("") + "|---|");
ROOMS.forEach(function (room) {
  var inRoom = products.filter(function (p) { return (p.rooms || []).indexOf(room) !== -1; });
  var cells = kinds.map(function (kind) {
    var n = inRoom.filter(function (p) { return p.subcategory === kind; }).length;
    return n ? String(n) : "—";
  });
  lines.push("| **" + room + "** | " + cells.join(" | ") + " | " + inRoom.length + " |");
});
lines.push("");

/* Full catalogue */
lines.push("## The catalogue");
lines.push("");
kinds.forEach(function (kind) {
  lines.push("### " + kind);
  lines.push("");
  products.filter(function (p) { return p.subcategory === kind; }).forEach(function (p) {
    var where = usedIn[p.slug] || [];
    lines.push("**" + p.name + "**  ");
    lines.push("`" + p.slug + "` · ASIN `" + asin(p.affiliateLink) + "`  ");
    lines.push("Rooms: " + ((p.rooms || []).join(", ") || "_none set_") + "  ");
    lines.push("Price: " + (p.price || "_not set_") + " · Photo: " + (p.image ? "yes" : "_none yet_") +
      " · Sizes link: " + (p.sizesLink ? "yes" : "_none_") + " · Colours link: " + (p.colorsLink ? "yes" : "_none_") + "  ");
    lines.push("Appears in: " + (where.length ? where.join(", ") : "_no article yet_"));
    lines.push("");
    lines.push("> " + p.description);
    lines.push("");
  });
});

/* Gaps */
lines.push("## Gaps worth filling");
lines.push("");
lines.push("Pieces the articles talk about that the shop does not carry yet, most useful first:");
lines.push("");
lines.push("| Piece | Why it matters |");
lines.push("|---|---|");
lines.push("| Table lamp | Every room article has a lighting section; the shop has one floor lamp |");
lines.push("| Throw or blanket | Named in the texture and cosy sections — cheap and rarely returned |");
lines.push("| Cushion covers | The easiest way to carry an accent colour, and an easy first sale |");
lines.push("| Nightstand | The bedroom article's bedside advice has nothing to link to |");
lines.push("| Side table | The reading corner and living-room sections both call for one |");
lines.push("| Bed frame | The bedroom article opens with the bed |");
lines.push("| Baskets | Named in every storage section |");
lines.push("| Dining table and chairs | The dining article's first two sections have no products |");
lines.push("| Pendant light | The dining lighting section has no product |");
lines.push("");

fs.writeFileSync(path.join(root, "CATALOGUE.md"), lines.join("\n"));
console.log("CATALOGUE.md written — " + products.length + " products, " + kinds.length + " kinds");
